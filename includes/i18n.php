/**
 * Translate a key
 */
function __($key, $fallback = null) {
    global $GLOBAL_TRANSLATIONS, $current_lang;
    $lang = $GLOBAL_TRANSLATIONS[$current_lang] ?? $GLOBAL_TRANSLATIONS['en'];
    return $lang[$key] ?? $fallback ?? $GLOBAL_TRANSLATIONS['en'][$key] ?? $key;
}
